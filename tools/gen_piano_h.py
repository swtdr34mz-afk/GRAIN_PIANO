"""res/piano.bin (tools/make_piano.py) as a C array in the firmware image: GRAIN PIANO carries its piano itself, so it
never depends on the resource region having been written. Run by the build (fm1.toml gen):
  tools/gen_piano_h.py --out GEN/piano_data.h"""
import pathlib, sys

out = pathlib.Path(sys.argv[sys.argv.index("--out") + 1])
src = pathlib.Path(__file__).resolve().parent.parent / "res" / "piano.bin"
b = src.read_bytes()
rows = ",\n".join(",".join(str(x) for x in b[i:i + 32]) for i in range(0, len(b), 32))
text = ("/* generated by tools/gen_piano_h.py from res/piano.bin: the Salamander Grand Piano V3 (Alexander Holm, "
        "CC-BY 3.0) */\n#pragma once\n#include <stdint.h>\n"
        f"#define PIANO_DATA_LEN {len(b)}u\n"
        "static const uint8_t piano_data[PIANO_DATA_LEN] __attribute__((aligned(4))) = {\n" + rows + "\n};\n")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
print(f"piano: {len(b)} B into {out}")
