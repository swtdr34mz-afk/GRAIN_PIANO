"""The splash's title, "Grain" over "Piano" in UnifrakturMaguntia (SIL OFL 1.1, assets/fonts), rasterised at build time:
its alpha (4 bits a pixel, 240 wide) and its grains (the pixels it breaks into: where, how fast, which way, how long
they glow). Run by the build (fm1.toml gen): tools/gen_title.py --out GEN/title_data.h  (needs Pillow)"""
import pathlib, random, sys
from PIL import Image, ImageDraw, ImageFont

out = pathlib.Path(sys.argv[sys.argv.index("--out") + 1])
root = pathlib.Path(__file__).resolve().parent.parent
font = ImageFont.truetype(str(root / "assets/fonts/UnifrakturMaguntia-Book.ttf"), 66)


def line(text):
    im = Image.new("L", (240, 100), 0)
    d = ImageDraw.Draw(im)
    b = d.textbbox((0, 0), text, font=font)
    d.text(((240 - (b[2] - b[0])) // 2 - b[0], 4 - b[1]), text, font=font, fill=255)
    return im.crop((0, im.getbbox()[1], 240, im.getbbox()[3]))


a, b = line("Grain"), line("Piano")
mask = Image.new("L", (240, a.size[1] + 8 + b.size[1]), 0)
mask.paste(a, (0, 0))
mask.paste(b, (0, a.size[1] + 8))
h = mask.size[1]
px = mask.load()
nib = [min(15, (px[x, y] + 8) // 17) for y in range(h) for x in range(240)]
data = bytes(nib[i] | nib[i + 1] << 4 for i in range(0, len(nib), 2))
random.seed(3)
grains = []
for y in range(h):
    for x in range(240):
        if px[x, y] > 100 and random.random() < 0.55:
            grains.append((x, y, random.randint(0, 255), random.randint(-128, 127), random.randint(0, 255)))
rows = lambda bs: ",\n".join(",".join(str(v) for v in bs[i:i + 32]) for i in range(0, len(bs), 32))
text = ("/* generated by tools/gen_title.py: the splash's title (UnifrakturMaguntia, SIL OFL 1.1) */\n#pragma once\n"
        "#include <stdint.h>\n"
        f"#define TITLE_W 240\n#define TITLE_H {h}\n#define TITLE_NG {len(grains)}\n"
        "static const uint8_t title_alpha[TITLE_W * TITLE_H / 2] = {\n" + rows(list(data)) + "\n};\n"
        "/* each grain: x, y, speed (0..255), drift (-128..127), its life (0..255) */\n"
        "static const uint8_t title_gx[TITLE_NG] = {\n" + rows([g[0] for g in grains]) + "\n};\n"
        "static const uint8_t title_gy[TITLE_NG] = {\n" + rows([g[1] for g in grains]) + "\n};\n"
        "static const uint8_t title_gs[TITLE_NG] = {\n" + rows([g[2] for g in grains]) + "\n};\n"
        "static const int8_t title_gd[TITLE_NG] = {\n" + rows([g[3] for g in grains]) + "\n};\n"
        "static const uint8_t title_gl[TITLE_NG] = {\n" + rows([g[4] for g in grains]) + "\n};\n")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
print(f"title: {h} px high, {len(grains)} grains into {out}")
