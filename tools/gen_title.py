"""The splash's title, GRAIN over PIANO in Press Start 2P (SIL OFL 1.1, assets/fonts): an 8-bit handheld's pixel type,
each pixel drawn 5 x 5, with a dark shadow; rasterised at build time: its alpha (4 bits a pixel, 240 wide) and its
grains (2 x 2 pieces it breaks into: where, how fast, which way, how long they glow). Run by the build (fm1.toml gen): tools/gen_title.py --out GEN/title_data.h  (needs Pillow)"""
import pathlib, random, sys
from PIL import Image, ImageDraw, ImageFont

out = pathlib.Path(sys.argv[sys.argv.index("--out") + 1])
root = pathlib.Path(__file__).resolve().parent.parent
font = ImageFont.truetype(str(root / "assets/fonts/PressStart2P-Regular.ttf"), 8)   # its own pixel grid: 8 px
SCALE, SHADOW, GAP = 5, 3, 12          # each pixel 5 x 5, a dark shadow 3 px down and right, 12 px between the lines


def line(text):                        # a line at 8 px, crisp (no smoothing), then blown up pixel by pixel
    im = Image.new("1", (8 * len(text) + 8, 12), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), text, font=font, fill=1)
    im = im.crop(im.getbbox())
    return im.resize((im.size[0] * SCALE, im.size[1] * SCALE), Image.NEAREST).convert("L")


a, b = line("GRAIN"), line("PIANO")
h = a.size[1] + GAP + b.size[1] + SHADOW
face = Image.new("L", (240, h), 0)
face.paste(a, ((240 - a.size[0]) // 2, 0))
face.paste(b, ((240 - b.size[0]) // 2, a.size[1] + GAP))
fp = face.load()
nib = []
for y in range(h):                     # 15: the gold face; 4: its shadow (dark bronze, as the gold dims it)
    for x in range(240):
        if fp[x, y] > 127: nib.append(15)
        elif x >= SHADOW and y >= SHADOW and fp[x - SHADOW, y - SHADOW] > 127: nib.append(4)
        else: nib.append(0)
data = bytes(nib[i] | nib[i + 1] << 4 for i in range(0, len(nib), 2))
random.seed(3)
grains = []                            # 2 x 2 grains (the screen's pixels are chunky here too), from the face
for y in range(0, h - 1, 2):
    for x in range(0, 240, 2):
        if fp[x, y] > 127 and random.random() < 0.9:
            grains.append((x, y, random.randint(0, 255), random.randint(-128, 127), random.randint(0, 255)))
byl = Image.new("1", (8 * 13, 10), 0)   # "by swtdr34mz" small, in the same type, 1 x
dd = ImageDraw.Draw(byl)
dd.fontmode = "1"
dd.text((0, 0), "by swtdr34mz", font=font, fill=1)
byl = byl.crop(byl.getbbox())
bw, bh = byl.size
bp = byl.load()
by_bits = [1 if bp[x, y] else 0 for y in range(bh) for x in range(bw)]
rows = lambda bs: ",\n".join(",".join(str(v) for v in bs[i:i + 32]) for i in range(0, len(bs), 32))
text = ("/* generated by tools/gen_title.py: the splash's title (Press Start 2P, SIL OFL 1.1) */\n#pragma once\n"
        "#include <stdint.h>\n"
        f"#define TITLE_W 240\n#define TITLE_H {h}\n#define TITLE_NG {len(grains)}\n"
        "static const uint8_t title_alpha[TITLE_W * TITLE_H / 2] = {\n" + rows(list(data)) + "\n};\n"
        "/* each grain: x, y, speed (0..255), drift (-128..127), its life (0..255) */\n"
        "static const uint8_t title_gx[TITLE_NG] = {\n" + rows([g[0] for g in grains]) + "\n};\n"
        "static const uint8_t title_gy[TITLE_NG] = {\n" + rows([g[1] for g in grains]) + "\n};\n"
        "static const uint8_t title_gs[TITLE_NG] = {\n" + rows([g[2] for g in grains]) + "\n};\n"
        "static const int8_t title_gd[TITLE_NG] = {\n" + rows([g[3] for g in grains]) + "\n};\n"
        "static const uint8_t title_gl[TITLE_NG] = {\n" + rows([g[4] for g in grains]) + "\n};\n"
        f"#define BY_W {bw}\n#define BY_H {bh}\n"
        "static const uint8_t title_by[BY_W * BY_H] = {\n" + rows(by_bits) + "\n};\n")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
print(f"title: {h} px high, {len(grains)} grains into {out}")
